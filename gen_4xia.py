# 生成 四下 8 单元 课本同步题库 -> cn45_4xia_pools.js
def js(s):
    s = s.replace('\\', '\\\\').replace("'", "\\'")
    return "'" + s + "'"

def emit_basic(it):
    t = it[0]
    if t == 'c':
        _, q, ans, opts = it
        return "    qs.push(mkChoice(" + js(q) + ", " + js(ans) + ", [" + ", ".join(js(o) for o in opts) + "]));"
    if t == 'f':
        _, q, ans = it
        return "    qs.push(mkFill(" + js(q) + ", " + js(ans) + "));"
    if t == 'j':
        _, q, b = it
        return "    qs.push(mkJudge(" + js(q) + ", " + ("true" if b else "false") + "));"

def emit_read(passage, items):
    out = []
    for it in items:
        t, q, ans, opts = it
        if t == 'c':
            out.append("    qs.push(cnRd(" + js(q) + ", " + js(ans) + ", [" + ", ".join(js(o) for o in opts) + "], " + js(passage) + "));")
        elif t == 'f':
            out.append("    qs.push(cnRdF(" + js(q) + ", " + js(ans) + ", " + js(passage) + "));")
    return "\n".join(out)

def emit_acc(it):
    t = it[0]
    if t == 'c':
        _, q, ans, opts = it
        return "    qs.push(cnAcc(" + js(q) + ", " + js(ans) + ", [" + ", ".join(js(o) for o in opts) + "]));"
    if t == 'f':
        _, q, ans = it
        return "    qs.push(cnAccF(" + js(q) + ", " + js(ans) + "));"
    if t == 'j':
        _, q, b = it
        return "    qs.push(cnAccJ(" + js(q) + ", " + ("true" if b else "false") + "));"

def unit_func(key, vocab, duo, basic, reads, acc):
    lines = ["  // ---- " + key + " ----",
             "  function " + key + "_pool() {",
             "    const qs = [];"]
    for py, wd in vocab:
        lines.append("    qs.push(mkFill(" + js("看拼音写词语：" + py + " →（    ）") + ", " + js(wd) + "));")
    for it in duo:
        lines.append(emit_basic(it))
    for it in basic:
        lines.append(emit_basic(it))
    for passage, items in reads:
        lines.append(emit_read(passage, items))
    for it in acc:
        lines.append(emit_acc(it))
    lines.append("    return qs;")
    lines.append("  }")
    return "\n".join(lines)

