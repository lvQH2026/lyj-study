  function ri(a, b) { return Math.floor(Math.random() * (b - a + 1)) + a; }
  function shuffle(a) { const r = a.slice(); for (let i = r.length - 1; i > 0; i--) { const j = ri(0, i); [r[i], r[j]] = [r[j], r[i]]; } return r; }
  function mkChoice(q, ans, opts) {
    var list;
    if (Array.isArray(opts)) list = opts.slice();
    else list = Array.prototype.slice.call(arguments, 2).map(function (x) { return Array.isArray(x) ? x[0] : x; });
    return { type: 'choice', question: q, options: shuffle([ans].concat(list)), answer: ans };
  }
  function mkFill(q, ans) { return { type: 'fill', question: q, answer: ans }; }
  function mkJudge(q, ans) { return { type: 'judge', question: q, answer: ans ? '正确' : '错误', options: ['正确', '错误'] }; }
  function mkFig(q, ans, opts, figName, a, b) {
    var it = mkChoice(q, ans, opts);
    var F = window.JRFIG;
    if (F && typeof F[figName] === 'function') {
      try { it.svg = F[figName](a, b); } catch (e) {}
    }
    return it;
  }

