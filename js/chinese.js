  // 考试中心：单元考试 / 期中考试 / 期末考试（真实试卷结构）
  // ============================================================
  function cnBuildExam(kind, arg) {
    const units = CN_DATA[cnState.grade] || [];
    const CN_NUM = ['\u96F6', '\u4E00', '\u4E8C', '\u4E09', '\u56DB', '\u4E94', '\u516D', '\u4E03', '\u516B', '\u4E5D'];
    let title = CN_NUM[cnState.grade] + '\u5E74\u7EA7\u8BED\u6587';
    let scope = units;
    let focus = null;
    if (kind === 'unit') {
      focus = units[arg];
      if (!focus) return null;
      scope = [focus];
      title += '《' + focus.name + '》测试卷';
    } else if (kind === 'mid' || kind === 'final') {
      if (cnState.grade === 6) {
        const term = arg === '\u4E0B' ? '\u4E0B' : '\u4E0A';
        const tb = units.filter(function (u) { return u.group === '\u8BFE\u672C' && u.term === term; });
        if (!tb.length) return null;
        scope = kind === 'mid' ? tb.slice(0, Math.ceil(tb.length / 2)) : tb;
        title += (term === '\u4E0A' ? '\u4E0A\u518C' : '\u4E0B\u518C') + (kind === 'mid' ? '\u671F\u4E2D\u6D4B\u8BD5\u5377' : '\u671F\u672B\u6D4B\u8BD5\u5377');
      } else {
        scope = kind === 'mid' ? units.slice(0, Math.ceil(units.length / 2)) : units;
        title += (kind === 'mid' ? '\u671F\u4E2D\u6D4B\u8BD5\u5377' : '\u671F\u672B\u6D4B\u8BD5\u5377');
      }
    }

    // 收集 scope 内全部题目（保留单元映射，供知识板块按 type 分类）
    const all = [];
    const allUnits = [];
    scope.forEach(function (u) {
      u.pool().forEach(function (q) { all.push(q); allUnits.push(u); });
    });

    // 分类：课本单元按 tag（read=阅读 / acc=积累，其余为基础）；知识板块按单元 type
    const isTextbook = scope.length && scope.every(function (u) { return u.group === '\u8BFE\u672C'; });
    function cnByType(typeArr) {
      const out = [];
      all.forEach(function (q, i) {
        if (typeArr.indexOf(allUnits[i].type) >= 0) out.push(q);
      });
      return out;
    }
    const basicQs = isTextbook ? all.filter(function (q) { return q.tag !== 'read' && q.tag !== 'acc'; }) : cnByType(['basic']);
    const readQs = isTextbook ? all.filter(function (q) { return q.tag === 'read' || (q.passage && q.tag !== 'acc'); }) : cnByType(['reading']);
    const accQs = isTextbook ? all.filter(function (q) { return q.tag === 'acc'; }) : cnByType(['poetry', 'application']);
    const fallback = all;
    const srcBase = basicQs.length ? basicQs : fallback;
    const srcRead = readQs.length ? readQs : fallback;
    const srcAcc = accQs.length ? accQs : fallback;

    const questions = [];
    const used = new Set();

    // 第一部分 · 基础知识（10题）
    let taken = 0;
    shuffle(srcBase).forEach(function (q) {
      if (taken >= 10 || used.has(q.question)) return;
      used.add(q.question);
      taken++;
      q.paperSection = '\u7B2C\u4E00\u90E8\u5206 \u00B7 \u57FA\u7840\u77E5\u8BC6';
      questions.push(q);
    });

    // 第二部分 · 阅读理解（2篇 × 4题）
    const groups = {};
    srcRead.forEach(function (q) {
      const key = q.passage || ('__p_' + (q.section || ''));
      if (!groups[key]) groups[key] = [];
      groups[key].push(q);
    });
    const keys = shuffle(Object.keys(groups).filter(function (k) { return groups[k].length >= 3; }));
    keys.slice(0, 2).forEach(function (k) {
      let tk = 0;
      shuffle(groups[k]).forEach(function (q) {
        if (tk >= 4 || used.has(q.question)) return;
        used.add(q.question);
        tk++;
        q.paperSection = '\u7B2C\u4E8C\u90E8\u5206 \u00B7 \u9605\u8BFB\u7406\u89E3';
        questions.push(q);
      });
    });

    // 第三部分 · 积累与运用（6题）
    const p3 = [];
    shuffle(srcAcc).forEach(function (q) {
      if (p3.length >= 6 || used.has(q.question)) return;
      used.add(q.question);
      p3.push(q);
    });
    if (p3.length < 6) {
      shuffle(srcBase).forEach(function (q) {
        if (p3.length >= 6 || used.has(q.question)) return;
        used.add(q.question);
        p3.push(q);
      });
    }
    p3.forEach(function (q) { q.paperSection = '\u7B2C\u4E09\u90E8\u5206 \u00B7 \u79EF\u7D2F\u4E0E\u8FD0\u7528'; questions.push(q); });

    questions.forEach(function (q) {
      if (!q.section) q.section = '\u8BED\u6587\u8003\u8BD5';
      if (!q.grade) q.grade = cnState.grade;
    });
    return { title: title, kind: kind, unitIdx: typeof arg === 'number' ? arg : 0, arg: arg, questions: questions };
  }

