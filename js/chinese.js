  // ---- 题库采样 ----
  function cnSamplePool(unit, n) {
    const pool = shuffle(unit.pool());
    const out = pool.slice(0, n);
    while (out.length < n && pool.length) out.push(pool[out.length % pool.length]);
    return out;
  }

  // 从多个单元轮转采样 n 题
  function cnSampleMulti(units, n) {
    const pools = units.map(function (u) { return shuffle(u.pool()); });
    const out = [];
    if (!pools.length) return out;
    let round = 0;
    while (out.length < n) {
      let added = false;
      for (let i = 0; i < pools.length && out.length < n; i++) {
        if (round < pools[i].length) { out.push(pools[i][round]); added = true; }
      }
      if (!added) break;
      round++;
    }
    return out;
  }

