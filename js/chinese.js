  function cnBuildExam(kind, unitIdx) {
    const units = CN_DATA[cnState.grade] || [];
    let title = cnState.grade + '年级语文';
    let scope = units;
    let focus = null;
    if (kind === 'unit') {
      focus = units[unitIdx];
      if (!focus) return null;
      title += '《' + focus.name + '》单元测试卷';
    } else if (kind === 'mid') {
      scope = units.slice(0, Math.ceil(units.length / 2));
      title += '期中测试卷';
    } else {
      title += '期末测试卷';
    }

    let basicUnits = scope.filter(function (u) { return u.type === 'basic'; });
    let readUnits = scope.filter(function (u) { return u.type === 'reading'; });
    let accUnits = scope.filter(function (u) { return u.type === 'poetry' || u.type === 'application'; });
    if (!readUnits.length) readUnits = units.filter(function (u) { return u.type === 'reading'; });
    if (!accUnits.length) accUnits = units.filter(function (u) { return u.type === 'poetry' || u.type === 'application'; });
    if (!basicUnits.length) basicUnits = units.filter(function (u) { return u.type === 'basic'; });

    const questions = [];

    // 第一部分 · 基础知识（10题）
    let p1 = [];
    if (focus && focus.type !== 'reading') {
      p1 = cnSamplePool(focus, 6).concat(cnSampleMulti(basicUnits, 4));
    } else {
      p1 = cnSampleMulti(basicUnits, 10);
    }
    p1.forEach(function (q) { q.paperSection = '第一部分 · 基础知识'; questions.push(q); });

    // 第二部分 · 阅读理解（2篇 × 4题）
    const groups = {};
    readUnits.forEach(function (u) {
      u.pool().forEach(function (q) {
        const key = q.passage || ('__p_' + u.name);
        if (!groups[key]) groups[key] = [];
        groups[key].push(q);
      });
    });
    const keys = shuffle(Object.keys(groups).filter(function (k) { return groups[k].length >= 3; }));
    keys.slice(0, 2).forEach(function (k) {
      shuffle(groups[k]).slice(0, 4).forEach(function (q) {
        q.paperSection = '第二部分 · 阅读理解';
        questions.push(q);
      });
    });

    // 第三部分 · 积累与运用（6题）
    let p3 = cnSampleMulti(accUnits, 6);
    if (p3.length < 6) p3 = p3.concat(cnSampleMulti(basicUnits, 6 - p3.length));
    p3.forEach(function (q) { q.paperSection = '第三部分 · 积累与运用'; questions.push(q); });

    questions.forEach(function (q) {
      if (!q.section) q.section = '语文考试';
      if (!q.grade) q.grade = cnState.grade;
    });
    return { title: title, kind: kind, unitIdx: unitIdx, questions: questions };
  }

