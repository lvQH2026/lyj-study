  function ri(a, b) { return Math.floor(Math.random() * (b - a + 1)) + a; }
  function shuffle(a) { const r = a.slice(); for (let i = r.length - 1; i > 0; i--) { const j = ri(0, i); [r[i], r[j]] = [r[j], r[i]]; } return r; }
