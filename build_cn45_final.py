def js(s):
    """Emit a single-quoted JS string literal, escaping backslash and single quote."""
    s = s.replace("\\", "\\\\").replace("'", "\\'")
    return "'" + s + "'"

# ----------------------------------------------------------------------------
# 1. Extract pool function blocks from the 4 generated files
# ----------------------------------------------------------------------------
def extract_pools(path):
    txt = open(path, encoding="utf-8").read()
    parts = re.split(r"\n\s*// ---- [a-z0-9]+ ----\s*\n", txt)
    blocks = []
    for seg in parts:
        m = re.search(r"function cn[45][sx][0-9]_pool\(\)\s*\{", seg)
        if not m:
            continue
        depth = 0
        i = seg.index("{", m.start())
        for j in range(i, len(seg)):
            if seg[j] == "{":
                depth += 1
            elif seg[j] == "}":
                depth -= 1
                if depth == 0:
                    end = j + 1
                    break
        blocks.append(seg[m.start():end])
    return blocks

all_blocks = []
for f in POOL_FILES:
    blks = extract_pools(f)
    print("extracted %d pools from %s" % (len(blks), f))
    all_blocks.extend(blks)
print("TOTAL pool blocks: %d" % len(all_blocks))
assert len(all_blocks) == 32, "expected 32 pool blocks"

